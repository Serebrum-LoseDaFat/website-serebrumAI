function WaveBlock({
  color,
  label,
  title,
  body,
}: {
  color: "emerald" | "cyan" | "violet";
  label: string;
  title: string;
  body: string;
}) {
  const colors = {
    emerald: {
      border: "border-black/[0.1]",
      bg: "bg-black/[0.02]",
      text: "text-neutral-400",
    },
    cyan: {
      border: "border-black/[0.1]",
      bg: "bg-black/[0.02]",
      text: "text-neutral-400",
    },
    violet: {
      border: "border-black/[0.1]",
      bg: "bg-black/[0.02]",
      text: "text-neutral-400",
    },
  };
  const c = colors[color];
  return (
    <div className={`rounded-xl border ${c.border} ${c.bg} px-6 py-5`}>
      <div className={`font-mono text-[10px] uppercase tracking-[0.22em] ${c.text} mb-2`}>
        {label}
      </div>
      <div className="text-base font-medium text-neutral-900 mb-2">{title}</div>
      <p
        className="text-sm leading-6 text-neutral-600"
        dangerouslySetInnerHTML={{ __html: body }}
      />
    </div>
  );
}
