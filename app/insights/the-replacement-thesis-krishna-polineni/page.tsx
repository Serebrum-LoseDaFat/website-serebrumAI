function SectionHeader({ number, title }: { number: string; title: string }) {
  return (
    <div className="mt-20 mb-8 flex items-start gap-5 pb-6 border-b border-white/[0.06]">
      <span className="mt-1 shrink-0 font-mono text-[11px] uppercase tracking-[0.25em] text-emerald-400 opacity-60">
        {number}
      </span>
      <h2 className="text-2xl font-medium tracking-tight text-neutral-50 md:text-3xl">
        {title}
      </h2>
    </div>
  );
}

function Prose({ children }: { children: React.ReactNode }) {
  return (
    <p className="mt-6 text-base leading-8 text-neutral-300 first:mt-0">
      {children}
    </p>
  );
}

function PullQuote({ children }: { children: React.ReactNode }) {
  return (
    <blockquote className="my-12 border-l-2 border-emerald-400/50 pl-7">
      <p className="font-serif text-xl italic leading-8 text-neutral-100 md:text-2xl">
        {children}
      </p>
    </blockquote>
  );
}

function Citation({ text }: { text: string }) {
  return (
    <span
      className="text-neutral-500 text-[13px]"
      dangerouslySetInnerHTML={{ __html: `(${text})` }}
    />
  );
}

function DataRow({ items }: { items: { label: string; value: string; sub: string }[] }) {
  return (
    <div className="my-10 grid grid-cols-2 gap-3 md:grid-cols-4">
      {items.map((item) => (
        <div
          key={item.label}
          className="rounded-xl border border-white/[0.08] bg-[#0a0a0d] px-5 py-4"
        >
          <div className="font-mono text-[9px] uppercase tracking-[0.2em] text-neutral-600 mb-2">
            {item.label}
          </div>
          <div className="text-base font-medium text-neutral-100">{item.value}</div>
          <div className="mt-1 text-xs text-emerald-400/70">{item.sub}</div>
        </div>
      ))}
    </div>
  );
}

function NumberedList({ items }: { items: { title: string; body: string }[] }) {
  return (
    <div className="my-10 space-y-6">
      {items.map((item, i) => (
        <div key={i} className="flex gap-6">
          <div className="shrink-0 mt-1">
            <span className="flex h-7 w-7 items-center justify-center rounded-full border border-emerald-400/30 bg-emerald-400/[0.08] font-mono text-[11px] text-emerald-300">
              {i + 1}
            </span>
          </div>
          <div>
            <div
              className="text-base font-medium text-neutral-100 mb-2"
              dangerouslySetInnerHTML={{ __html: item.title }}
            />
            <p
              className="text-sm leading-7 text-neutral-400"
              dangerouslySetInnerHTML={{ __html: item.body }}
            />
          </div>
        </div>
      ))}
    </div>
  );
}

function WaveBlock({
  color,
  label,
  title,
  body,
}: {
  color: "emerald" | "cyan" | "violet";
  label: string;
  title: string;
  body: string;
}) {
  const colors = {
    emerald: {
      border: "border-emerald-400/20",
      bg: "bg-emerald-400/[0.04]",
      text: "text-emerald-300",
    },
    cyan: {
      border: "border-cyan-400/20",
      bg: "bg-cyan-400/[0.04]",
      text: "text-cyan-300",
    },
    violet: {
      border: "border-violet-400/20",
      bg: "bg-violet-400/[0.04]",
      text: "text-violet-300",
    },
  };
  const c = colors[color];
  return (
    <div className={`rounded-xl border ${c.border} ${c.bg} px-6 py-5`}>
      <div className={`font-mono text-[10px] uppercase tracking-[0.22em] ${c.text} mb-2`}>
        {label}
      </div>
      <div className="text-base font-medium text-neutral-100 mb-2">{title}</div>
      <p
        className="text-sm leading-6 text-neutral-400"
        dangerouslySetInnerHTML={{ __html: body }}
      />
    </div>
  );
}
